let currentLang = "es";

function buildWaLink(number, text){
  return "https://wa.me/" + number + (text ? ("?text=" + encodeURIComponent(text)) : "");
}

function applyLang(lang){
  currentLang = lang;
  document.documentElement.lang = lang;
  const dict = translations[lang];
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key = el.getAttribute("data-i18n");
    if(dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el=>{
    const key = el.getAttribute("data-i18n-placeholder");
    if(dict[key]) el.setAttribute("placeholder", dict[key]);
  });
  document.querySelectorAll(".lang-switch button").forEach(b=>{
    b.classList.toggle("active", b.getAttribute("data-lang") === lang);
  });
  const defaultWaText = dict["wa.greeting"];
  document.getElementById("hero-wa-btn").href = buildWaLink(WA_NUMBER, defaultWaText);
  document.getElementById("header-wa-btn").href = buildWaLink(WA_NUMBER, defaultWaText);
  document.getElementById("header-wa-btn-mobile").href = buildWaLink(WA_NUMBER, defaultWaText);
  document.getElementById("wa-float").href = buildWaLink(WA_NUMBER, defaultWaText);
  document.getElementById("footer-wa").href = buildWaLink(WA_NUMBER, defaultWaText);
  document.getElementById("contact-phone-link").href = buildWaLink(WA_NUMBER, defaultWaText);
}

document.querySelectorAll(".lang-switch button").forEach(btn=>{
  btn.addEventListener("click", ()=> applyLang(btn.getAttribute("data-lang")));
});

