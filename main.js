document.getElementById("contact-form").addEventListener("submit", function(e){
  e.preventDefault();
  const dict = translations[currentLang];
  const name = document.getElementById("f-name").value.trim();
  const email = document.getElementById("f-email").value.trim();
  const subjectSelect = document.getElementById("f-subject");
  const subjectLabel = subjectSelect.options[subjectSelect.selectedIndex].text;
  const message = document.getElementById("f-message").value.trim();

  let text = dict["wa.greeting"] + "\n\n";
  text += dict["wa.name"] + ": " + (name || "-") + "\n";
  text += dict["wa.email"] + ": " + (email || "-") + "\n";
  text += dict["wa.subject"] + ": " + subjectLabel + "\n";
  text += dict["wa.message"] + ": " + (message || "-");

  window.open(buildWaLink(WA_NUMBER, text), "_blank");
});

